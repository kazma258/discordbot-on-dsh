import { dump } from 'js-yaml';

export const DISCORD_PRESET_ID = 'discord-whale';

const PRESET_ID_PATTERN = /^[a-z0-9][a-z0-9-]*$/;

export const DISCORD_BRIDGE_PROTOCOL = `## 橋接協議（最高優先）
- 你會收到以 \`[需回覆]\` 或 \`[僅記錄]\` 開頭的 Discord 訊息。
- \`[需回覆]\`：必須回覆該訊息；絕對不要輸出 \`[SILENT]\`；只輸出要發到 Discord 的內容，不要描述自己的動作。
- \`[僅記錄]\`：只需閱讀；若沒有特別想說的，輸出 \`[SILENT]\`。
- 不要提到橋接、session、prompt、模型或系統訊息。
- 不要使用 Markdown；不要 @everyone、身分組或使用者。`;

const COMPACTION_PLUGINS = [
  {
    id: 'compaction',
    name: 'cordis:group',
    group: true,
    isolate: { compaction: true },
    config: [
      { id: 'compaction-basic', name: '@deepseek-ai/dsh-compaction-basic' },
      { id: 'command-compact', name: '@deepseek-ai/dsh-command-compact' }
    ]
  }
];

function normalizePersona(text: string): string {
  return text.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n').trim();
}

/**
 * The exact system-prompt text used by both the DSH preset and the direct-API
 * persona comparison: character card plus the Discord bridge protocol.
 */
export function buildPersonaPrompt(personaText: string): string {
  const persona = normalizePersona(personaText);
  if (persona === '') throw new Error('persona/character.md is empty');
  return `${persona}\n\n${DISCORD_BRIDGE_PROTOCOL}`;
}

/**
 * Generate a DSH 0.2.1 profile-bundle patch with one restricted chat preset.
 * The preset deliberately mounts no shell, filesystem, job, subagent,
 * workflow, MCP-resource, or plugin-manager rows.
 */
export function buildDiscordPresetPatch(
  personaText: string,
  presetId = DISCORD_PRESET_ID
): string {
  if (!PRESET_ID_PATTERN.test(presetId)) {
    throw new Error(`invalid DSH preset id: ${presetId}`);
  }

  const personaPrompt = buildPersonaPrompt(personaText);

  const patch = [
    {
      insert: [
        {
          id: `preset-${presetId}`,
          name: '@deepseek-ai/dsh-agent-preset',
          config: {
            id: presetId,
            name: 'Discord 小鯨魚',
            description: 'Discord 橋接用的受限聊天角色；沒有 shell、檔案或子代理工具。',
            order: 20,
            plugins: [
              {
                id: 'persona',
                name: '@deepseek-ai/dsh-persona',
                config: {
                  prefix: personaPrompt,
                  complete: true,
                  includeRuntimeContext: false
                }
              },
              ...COMPACTION_PLUGINS
            ]
          }
        }
      ]
    }
  ];

  const header =
    '# Generated by scripts/build-preset.ts from persona/character.md.\n' +
    '# Do not edit by hand; change the persona file or the build script instead.\n';
  return `${header}${dump(patch, { lineWidth: -1, noRefs: true })}`;
}
